package edu.scut.nqueens.blackboard;

/**
 * 知识源（Knowledge Source）：一条<b>独立的</b>问题求解规则。
 *
 * <p><b>本接口的形状就是黑板架构的核心约束：</b>
 * {@link #canHandle} 与 {@link #execute} 的入参<b>只有黑板</b>——
 * 知识源拿不到任何其它知识源的引用，因此"知识源之间绝对无直接通信"
 * 不是靠自觉遵守，而是在类型系统上就写不出来。
 * 知识源 A 产生的结果只能写进黑板，由知识源 B 自己去黑板读取，
 * 二者在代码层面互不可见、互不知情。
 *
 * <p><b>知识源必须满足的三条性质：</b>
 * <ol>
 *   <li><b>独立</b>：只依赖黑板的内容，不依赖其它知识源是否执行过；</li>
 *   <li><b>可单独触发</b>：{@link #canHandle} 只看黑板当前状态就能决定自己要不要出手；</li>
 *   <li><b>可替换</b>：换成另一套等价规则（例如不同的剪枝实现）不应影响其它知识源。</li>
 * </ol>
 *
 * <p>实现类建议为无状态对象（构造时注入 {@code BitVectorPruner} 这类无状态协作者即可），
 * 这样多个知识源并行触发时也不会产生共享可变状态。
 */
public interface KnowledgeSource {

    /** 知识源名称，用于日志与 C&amp;C 图对照（如"列约束检查"）。 */
    String name();

    /**
     * 触发条件：黑板当前状态是否满足本知识源出手的条件。
     *
     * <p>TODO（各知识源自行实现）：只能读黑板，不能修改黑板，
     * 也不得依赖"其它知识源是否已经跑过"这种外部信息。
     *
     * @param blackboard 黑板存储区
     * @return 满足条件返回 true
     */
    boolean canHandle(BlackboardState blackboard);

    /**
     * 执行本知识源的求解动作：读黑板 → 计算 → 把结果写回黑板。
     *
     * <p>TODO（各知识源自行实现）：实现中禁止持有或调用其它知识源；
     * 需要的东西全部从 {@code blackboard} 里取。
     *
     * @param blackboard 黑板存储区
     */
    void execute(BlackboardState blackboard);
}
