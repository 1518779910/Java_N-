package edu.scut.nqueens.common;

/**
 * 统一的位向量剪枝算法接口模板。
 *
 * <p><b>为什么要有这个接口：</b>作业要求"五种方案的剪枝策略必须等价（均采用列占用 +
 * 两条对角线占用的相同位向量剪枝），以保证跨架构性能对比公平"。把剪枝收敛到这一个
 * 接口上，等价性就不再依赖人工检查，而是由"五种架构调用同一份实现"在结构上保证。
 *
 * <p><b>实现要求：</b>
 * <ul>
 *   <li>实现类必须<b>无状态</b>（所有字段 static final 或没有字段），可以被多线程共享；</li>
 *   <li>{@code canPlace} 与 {@code place} 必须是纯函数：相同入参必得相同结果，且不修改入参；</li>
 *   <li>实现类不得引用 pipesfilter、blackboard 等任何架构包下的类型。</li>
 * </ul>
 *
 * <p><b>责任人：</b>成员A（组长）。其余成员如需扩展剪枝规则，必须先在本接口上达成一致。
 */
public interface BitVectorPruner {

    /**
     * 初始剪枝状态：棋盘为空，尚未放置任何皇后。
     *
     * @param n 棋盘规模
     */
    BitVectorBoardState initial(int n);

    /**
     * 判断在 {@code (row, col)} 放置皇后是否不与任何已放置的皇后冲突。
     *
     * <p>TODO（成员A）：用三次按位与实现列冲突与两条对角线冲突检查，禁止用循环逐格扫描。
     *
     * @param state 当前剪枝状态
     * @param row   待放置的行号（0-based）
     * @param col   待放置的列号（0-based）
     * @return 合法返回 true；与已有皇后同列或同对角线返回 false
     */
    boolean canPlace(BitVectorBoardState state, int row, int col);

    /**
     * 在 {@code (row, col)} 放置一个皇后，返回放置后的<b>新</b>状态。
     *
     * <p>TODO（成员A）：用按位或把列与两条对角线对应的位置 1；不得修改传入的 state。
     *
     * @param state 放置前的剪枝状态
     * @param row   行号（0-based）
     * @param col   列号（0-based）
     * @return 放置后的新状态（不可变对象）
     */
    BitVectorBoardState place(BitVectorBoardState state, int row, int col);
}
